        public static string English(string text)
        {
            if (string.IsNullOrEmpty(text)) return text;
            if (Cache.TryGetValue(text, out var translated)) return translated;
            translated = text;
            for (int i=0; i<Phrases.GetLength(0); i++) translated = translated.Replace(Phrases[i,0], Phrases[i,1]);
            if (Cache.Count > 512) Cache.Clear();
            Cache[text] = translated;
            return translated;
        }
